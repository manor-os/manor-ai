# A supported preference may use English UI fallbacks while AI still receives
# the selected language. Keep the Web and mobile language choices valid here.
SUPPORTED_LOCALES = set(TRANSLATIONS.keys()) | {"de", "vi"}


def set_locale(locale: str) -> None:
    """Set the current request's locale (thread/task-local)."""
    _locale_var.set(locale if locale in SUPPORTED_LOCALES else "en")


def get_locale() -> str:
    """Return the current request's locale."""
    return _locale_var.get()


_KANA_RE = re.compile(r"[\u3040-\u30ff]")
_CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def text_locale(text: str) -> str | None:
    """``zh``/``ja`` for Chinese/Japanese text, else None (use the current locale)."""
    sample = str(text or "")[:400]
    if _KANA_RE.search(sample):
        return "ja"
    letters = sum(1 for char in sample if char.isalpha())
    if letters and len(_CJK_RE.findall(sample)) * 3 >= letters:
        return "zh"
    return None


def t(key: str, locale: Optional[str] = None, **kwargs: object) -> str:
    """Translate a key. Falls back to English, then to the key itself."""
    loc = locale or get_locale()
    msg = TRANSLATIONS.get(loc, {}).get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            msg = msg.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return msg
